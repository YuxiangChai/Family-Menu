const test = require('node:test')
const assert = require('node:assert/strict')
const { mkdtempSync, rmSync, existsSync } = require('node:fs')
const { execFileSync } = require('node:child_process')
const path = require('node:path')
const os = require('node:os')
const { Store } = require('../store')
const { readConfig } = require('../config')

test('本机管理员授权、名单脱敏、停用、重启持久化和空库备份', (t) => {
  const temporary = mkdtempSync(path.join(os.tmpdir(), 'family-menu-cli-'))
  t.after(() => rmSync(temporary, { recursive: true, force: true }))
  const dataDir = path.join(temporary, 'data')
  const cli = (...args) => execFileSync(process.execPath, [path.join(__dirname, '../cli.js'), ...args], {
    env: { ...process.env, MENU_DATA_DIR: dataDir, PORT: '3000', PUBLIC_BASE_URL: 'http://127.0.0.1:3000' }, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe']
  })
  cli('admin', '--openid', 'test-cli-admin-openid', '--nickname', '测试管理员')
  let store = new Store(dataDir)
  const admin = store.member('test-cli-admin-openid')
  assert.equal(admin.role, 'admin')
  assert.equal(store.all('dishes').length, 0)
  assert.equal(store.all('categories').length, 9)
  store.saveMember({ ...admin, _id: undefined, nickname: '改名' })
  assert.equal(store.member(admin.openid)._id, admin._id)
  store.close()
  assert(!cli('members').includes(admin.openid))
  assert(cli('members', '--show-openids').includes(admin.openid))
  assert.throws(() => cli('member', '--openid', admin.openid, '--enabled', 'false'), /不能停用管理员/)
  assert.throws(() => cli('admin', '--openid', 'test-second-admin-openid'), /不能新增或转让管理员/)
  cli('member', '--openid', 'test-cli-member-openid', '--enabled', 'false')
  store = new Store(dataDir)
  assert.equal(store.member(admin.openid).enabled, true)
  assert.equal(store.member(admin.openid).role, 'admin')
  assert.equal(store.member('test-cli-member-openid').enabled, false)
  assert.throws(() => cli('member', '--openid', 'test-cli-member-openid', '--chef', 'true'), /Unknown option/)
  assert.equal(store.member('test-cli-member-openid').role, 'member')
  store.close()
  const destination = path.join(temporary, 'backup')
  cli('backup', '--output', destination)
  assert(existsSync(path.join(destination, 'uploads')))
  store = new Store(destination)
  assert.equal(store.member(admin.openid).enabled, true)
  assert.equal(store.member('test-cli-member-openid').enabled, false)
  store.close()
  assert.throws(() => cli('backup', '--output', destination), /备份目录已存在/)
  assert.throws(() => cli('backup', '--output', path.join(dataDir, 'uploads', 'nested-backup')), /不能放在 uploads 内/)
})

test('服务配置只允许 HTTPS 或本机 HTTP，不接受 URL 中的账号和路径', () => {
  assert.equal(readConfig({}).host, '127.0.0.1')
  assert.equal(readConfig({ PUBLIC_BASE_URL: 'https://menu.example.com' }).publicUrl, 'https://menu.example.com')
  for (const value of ['http://192.168.1.2', 'https://user:password@example.com', 'https://example.com/api', 'https://example.com?secret=1']) {
    assert.throws(() => readConfig({ PUBLIC_BASE_URL: value }))
  }
  assert.throws(() => readConfig({ PORT: '-1' }))
})
